// normalizeWord（本ファイル下部で定義）で表記ゆれを吸収する。
function matchDummyAnswer(puzzle, input) {
  const v = normalizeWord(input);
  if (!v) return false;
  return puzzle.answers.some(function (a) { return normalizeWord(a) === v; });
}

