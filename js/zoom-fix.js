// ========================================
// 画面が切り替わったら、必ずページ先頭・等倍で見せるための処理
// ========================================
// ■ 分かったこと（重要・今後さわる人へ）
// iOS Safari は10以降、アクセシビリティのために viewport の
// user-scalable=no / maximum-scale を「意図的に無視」する仕様になっている。
// そのため「metaタグを一瞬だけ拡大禁止に差し替えて拡大率を1.0に戻す」
// という定番の小細工は、iPhoneのSafariでは効かない。
// （実際この方法をタイミングを変えて何度も調整して試したが、実機では
//   一度も直らなかった。さらに、拡大した状態でmetaタグを何度も差し替えると
//   再レイアウトが重なって操作不能になる＝固まることがあった。）
//
// JavaScript から iOS Safari のピンチ拡大率を戻すAPIは存在しない。
// 唯一確実に等倍へ戻るのは「新しいページを実際に読み込んだとき」。
//
// ■ そこでの方針
// ・ここでは拡大率をいじらない（スクロール位置だけ先頭へ戻す）。
// ・「アドレスは変わらないまま画面だけ差し替える」場面をやめ、
//   実際にページを読み込み直す（URLに stage= などを付けて遷移する）
//   ことで、ブラウザ自身に等倍へ戻してもらう。
//   ※同じURLへの遷移は「再読み込み」扱いになり拡大率が保持されるため、
//     必ずクエリを変えて「別のURL」として読み込ませること。
(function () {
  // 画面の切り替え後に呼ぶ共通関数。
  // 拡大率には触らない（触っても効かず、固まる原因になるため）。
  window.resetZoomAndScroll = function () {
    window.scrollTo(0, 0);
  };

  // 以前あった「拡大率だけ即座に戻す」関数。効果がないことが分かったので
  // 中身は空にしてある（呼び出しが残っていてもエラーにならないように）。
  window.resetZoomOnly = function () {};
})();
